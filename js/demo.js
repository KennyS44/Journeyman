  /** Файл из папки demo/ — как File, чтобы у вложения было имя. */
  async function fetchFile(src, name) {
    const res = await fetch(src, { cache: 'force-cache' });
    if (!res.ok) throw new Error(src + ' — ' + res.status);
    const blob = await res.blob();
    return new File([blob], name, { type: blob.type || 'application/octet-stream' });
  }

  async function build() {
    const space = await DB.createSpace(SPACE.name, SPACE.description);
    const byKey = {};

    for (const spec of NODES) {
      const node = await DB.createNode(space.id, spec.name, spec.x, spec.y);
      byKey[spec.key] = node;

      const cover = COVERS[spec.cover];
      const image = await DB.addAsset(node.id, await fetchFile(cover.src, cover.name), 'image');

      const track = TRACKS[spec.track];
      await DB.addAsset(node.id, await fetchFile(track.src, track.name), 'audio');

      const now = Date.now();
      await DB.updateNode(node.id, {
        coverId: image.id,                    // обложка карточки на холсте
        html: spec.html,
        text: spec.html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim(),
        notes: spec.notes.map((text, i) => ({ id: DB.uid(), text, createdAt: now + i })),
      });
    }

    for (const [a, b, label] of LINKS) {
      await DB.createLink(space.id, byKey[a].id, byKey[b].id, label);
    }
    return space;
  }

  /** Разложить сцену — только на пустом хранилище и только один раз. */
  async function seedIfEmpty() {
    let seeded;
    try { seeded = localStorage.getItem(FLAG); } catch (_) { return; }
    if (seeded) return;

    const spaces = await DB.listSpaces();
    if (spaces.length) {                      // у человека уже есть свои записи
      try { localStorage.setItem(FLAG, '1'); } catch (_) {}
      return;
    }

    try {
      await build();
    } catch (err) {
      console.error('Демо-сцену собрать не удалось:', err);
      return;                                 // без флага: попробуем в следующий раз
    }
    try { localStorage.setItem(FLAG, '1'); } catch (_) {}
  }

  return { seedIfEmpty };
